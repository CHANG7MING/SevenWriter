from __future__ import annotations

import re


def scene_score(text: str, scene: str) -> tuple[float, list[str]]:
    checks = {
        "seo": [(r"^#\s", "缺少清晰 H1"), (r"^##\s", "缺少可扫描的小节"), (r"\?|？|什么|如何|为什么", "没有明显回应搜索问题")],
        "geo": [(r"来源|根据|数据|截至|定义", "缺少来源、时间或定义边界"), (r"限制|适用|取决于|可能", "缺少限制条件")],
        "xiaohongshu": [(r"我|我们|适合|不适合|优点|缺点", "缺少身份、对象或具体判断")],
        "short-video": [(r"。|！|？|\n", "缺少口播停顿"), (r"你|如果|先|第一步|最后", "缺少听众指向或递进")],
        "email": [(r"您好|你好|Hi|尊敬", "可能缺少恰当称呼"), (r"回复|确认|请|预计|时间|附件|下一步", "缺少明确动作或时间")],
        "speech": [(r"我们|各位|今天|大家", "缺少听众或场合指向"), (r"\[停顿\]|\n", "缺少可朗读停顿")],
        "website": [(r"立即|开始|了解|联系|试用|购买|申请", "缺少明确 CTA")],
        "longform": [(r"^#{1,3}\s", "缺少文档层级")],
        "customer-progress": [(r"当前|已经|正在|尚未", "缺少当前状态"), (r"预计|今天|明天|本周|时间", "缺少时间边界"), (r"回复|同步|确认|下一步", "缺少下一步动作")],
        "after-sales": [(r"订单|退款|物流|快递|售后", "缺少问题对象"), (r"预计|工作日|时间|状态", "缺少处理时间或状态"), (r"请|需要|提供|核对", "缺少下一步")],
        "interview-followup": [(r"面试|岗位|申请", "缺少面试或岗位上下文"), (r"进展|结果|时间|后续", "缺少明确询问")],
        "wechat-message": [(r"。|！|？|\n", "消息可能缺少自然停顿")],
        "community-notice": [(r"时间|地点|对象|请|截止", "通知缺少关键信息")],
        "product-recommendation": [(r"适合|不适合|优点|限制|场景", "缺少适用对象或限制")],
        "self-media-longform": [(r"^#{1,3}\s|\n\n", "长文缺少可扫描结构"), (r"例子|数据|具体|问题", "缺少具体信息")],
        "wechat-official-account": [(r"^#{1,3}\s|\n\n", "公众号文章缺少可扫描结构"), (r"例子|数据|具体|问题|步骤", "正文缺少具体信息或推进")],
        "wechat-moments": [(r"我|我们|今天|刚刚|最近|这次|分享", "缺少发布者视角或具体语境"), (r"。|！|？|\n", "缺少适合朋友圈阅读的自然停顿")],
        "podcast": [(r"主持|嘉宾|听众|本期|节目", "缺少节目角色或听众定位"), (r"\n|接下来|回到|最后", "缺少听觉转场或段落推进")],
        "weekly-report": [(r"本周|完成|进展|结果", "缺少本周结果"), (r"下周|下一步|计划|阻塞|风险", "缺少下一步或风险")],
        "agreement": [(r"甲方|乙方|双方|用户|平台|主体", "缺少义务主体"), (r"应当|不得|有权|期限|条件|责任", "缺少权利义务、条件或期限")],
        "ppt": [(r"^#|标题|结论", "缺少页面结论或标题"), (r"数据|来源|依据|备注|要点", "缺少支撑信息或来源提示")],
        "bio": [(r"负责|从事|现任|曾任|作品|研究|经验", "缺少具体身份或经历"), (r"年|届|期间|目前|现", "可能缺少时间边界")],
        "academic": [(r"研究|方法|数据|结果|结论|文献", "缺少研究或论证要素"), (r"可能|表明|相关|限制|不足", "缺少不确定性或研究边界")],
        "game-copy": [(r"玩家|角色|活动|奖励|版本|玩法", "缺少游戏对象或玩法上下文"), (r"时间|概率|条件|限制|规则", "缺少活动或付费边界")],
        "compliance": [(r"证据|来源|授权|许可|依据|待确认", "缺少证据或权利依据"), (r"适用|限制|地区|平台|披露|风险", "缺少适用范围或风险限定")],
    }
    selected = checks.get(scene, [])
    if not selected:
        return 3.8, []
    misses = [message for pattern, message in selected if not re.search(pattern, text, re.M | re.I)]
    return round(max(1.0, 5.0 - len(misses) * (2.0 / max(1, len(selected)))), 2), misses
